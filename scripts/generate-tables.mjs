#!/usr/bin/env node
/**
 * Generate the documentation tables that must not drift from the code:
 *
 *   docs/SHORTCUTS.md  from `PLURID_SHORTCUTS` / `PLURID_POINTER_GESTURES` / `PLURID_SHORTCUT_GROUP_TITLES`
 *                      in @plurid/plurid-data (the bindings the engine dispatches, the `?` overlay shows);
 *   docs/CHANGES.md    from `PLURID_CHANGE_KINDS` in @plurid/plurid-data (every kind a `space.changed` carries);
 *   docs/HARNESS.md    from the render-test harness's FLAG REGISTRY (`fixtures/render-test/src/harness/flags.ts`)
 *                      and FIXTURE CATALOG (`fixtures/render-test/src/fixtures/catalog.ts`) — every `?flag=`
 *                      the harness understands and every fixture the browser suites verify;
 *   docs/LOOKS.md      from `LOOK_TOKENS` / `LOOK_BASES` / `looks` in `@plurid/plurid-themes`.
 *
 *   pnpm docs.tables          # rewrite all four (needs @plurid/plurid-data and @plurid/plurid-themes built;
 *                             # Node ≥ 22.18 / 23.6 imports the .ts registries directly)
 *   pnpm docs.tables --check  # exit 1 when any of them is stale (part of `pnpm verify`)
 */
import { createRequire } from 'node:module';
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { ASSERTION_GLOBALS, expectationsText, namedGlobals, publishedGlobals, stepText, undocumentedGlobals } from './harness-tables.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
const require = createRequire(import.meta.url);
const check = process.argv.includes('--check');

// The harness's registries are TypeScript, imported as they are. A Node that cannot strip types failed
// further down with ERR_UNKNOWN_FILE_EXTENSION from flags.ts (2026-10-20).
if (!process.features.typescript) {
    console.error('[docs.tables] needs Node ≥ 22.18 (or ≥ 23.6), which imports .ts files directly: '
        + process.version + ' does not strip types here.');
    process.exit(1);
}

const emit = (relative, output, summary) => {
    const target = resolve(root, relative);
    if (check) {
        const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
        if (current !== output) {
            console.error('[docs.tables] ' + relative + ' is stale — run `pnpm docs.tables`');
            process.exit(1);
        }
        console.log('[docs.tables] ' + relative + ' is current');
    } else {
        writeFileSync(target, output);
        console.log('[docs.tables] wrote ' + relative + ' (' + summary + ')');
    }
};


// #region shortcuts
const dataPackage = resolve(root, 'packages/plurid-web/plurid-core/plurid-data');
const distribution = resolve(dataPackage, 'distribution/index.js');

if (!existsSync(distribution)) {
    console.error('[docs.tables] build @plurid/plurid-data first: pnpm --filter @plurid/plurid-data build');
    process.exit(1);
}

const data = require(distribution);
const shortcuts = data.PLURID_SHORTCUTS;
const gestures = data.PLURID_POINTER_GESTURES;
const titles = data.PLURID_SHORTCUT_GROUP_TITLES || {};

const label = (code) => {
    const names = {
        Space: 'Space', Escape: 'Esc', Tab: 'Tab', Period: '.', Comma: ',', Slash: '/', Backslash: '\\',
        Minus: '-', Equal: '=', ShiftLeft: 'Shift', ShiftRight: 'Shift', Enter: 'Enter', Home: 'Home', End: 'End',
        ArrowUp: '↑', ArrowDown: '↓', ArrowLeft: '←', ArrowRight: '→',
    };
    if (names[code]) return names[code];
    if (/^Key.$/.test(code)) return code.slice(3);
    if (/^Digit.$/.test(code)) return code.slice(5);
    return code;
};

const keysOf = (definition) => {
    const parts = [];
    if (definition.modifiers?.ctrlOrMeta) parts.push('⌘/Ctrl');
    if (definition.modifiers?.alt) parts.push('Alt');
    if (definition.modifiers?.shift) parts.push('Shift');
    if (definition.keys) parts.push(...definition.keys);
    else if (definition.code) parts.push(label(definition.code));
    return parts.map((part) => '`' + part + '`').join(' + ');
};

const groups = new Map();
for (const definition of shortcuts) {
    const list = groups.get(definition.group) || [];
    list.push(definition);
    groups.set(definition.group, list);
}

const shortcutLines = [];
shortcutLines.push('# Keyboard shortcuts and pointer gestures');
shortcutLines.push('');
shortcutLines.push('GENERATED by `scripts/generate-tables.mjs` from `PLURID_SHORTCUTS` / `PLURID_POINTER_GESTURES` in `@plurid/plurid-data` — do not edit; run `pnpm docs.tables`. Every shortcut can be disabled or remapped through `space.shortcuts` (see CONTROL_SURFACE.md); `hold` shortcuts act while the key is down; `when` names the mode the shortcut needs (`page`: the page presentation; `grabMode`; `firstPerson`).');
shortcutLines.push('');
shortcutLines.push('PRECEDENCE: the dispatcher walks its table in order and the first binding whose condition holds runs; for a shared key the rows above win — `Escape` is `dock` (the page presentation: from the revealed space, or docked on a spawned page) before `exitGrabMode`, then the selection is cleared. Inside plane CONTENT (a focused field, a list, a link, a docked page\'s scroller) the arrows, Enter, Home and Space are the page\'s, never shortcuts. On a docked page `G` reveals the space as it enters grab mode, and `0` (fit) is a legitimate undock.');
shortcutLines.push('');
for (const [group, list] of groups) {
    shortcutLines.push('## ' + (titles[group] || group));
    shortcutLines.push('');
    shortcutLines.push('| Keys | Action | Id | Kind | When |');
    shortcutLines.push('| --- | --- | --- | --- | --- |');
    for (const definition of list) {
        shortcutLines.push(`| ${keysOf(definition)} | ${definition.label} | \`${definition.id}\` | ${definition.kind} | ${definition.when || '-'} |`);
    }
    shortcutLines.push('');
}
shortcutLines.push('## Pointer');
shortcutLines.push('');
shortcutLines.push('| Input | Action |');
shortcutLines.push('| --- | --- |');
for (const gesture of gestures) {
    shortcutLines.push(`| ${gesture.keys.map((key) => '`' + key + '`').join(' + ')} | ${gesture.label} |`);
}
shortcutLines.push('');

emit('docs/SHORTCUTS.md', shortcutLines.join('\n'), shortcuts.length + ' shortcuts, ' + gestures.length + ' gestures');
// #endregion shortcuts


// #region changes
// docs/CHANGES.md — every kind a `space.changed` can carry, from `PLURID_CHANGE_KINDS`
const kinds = data.PLURID_CHANGE_KINDS || [];
const changeLines = [];
changeLines.push('# `space.changed`: every kind');
changeLines.push('');
changeLines.push('GENERATED by `scripts/generate-tables.mjs` from `PLURID_CHANGE_KINDS` in `@plurid/plurid-data` — do not edit; run `pnpm docs.tables`. A host subscribes once to `space.changed` and reads `{ kind, value }`; `PluridChangeKind` is the type of `kind`, and a test holds it equal to this list.');
changeLines.push('');
changeLines.push('| kind | value |');
changeLines.push('| --- | --- |');
for (const [kind, note] of kinds) {
    changeLines.push('| `' + kind + '` | ' + String(note).replace(/\|/g, '\\|') + ' |');
}
changeLines.push('');
emit('docs/CHANGES.md', changeLines.join('\n'), kinds.length + ' change kinds');
// #endregion changes


// #region harness
const harness = resolve(root, 'fixtures/render-test/src');
const { FLAGS } = await import(pathToFileURL(resolve(harness, 'harness/flags.ts')).href);
const { FIXTURES } = await import(pathToFileURL(resolve(harness, 'fixtures/catalog.ts')).href);

const cell = (text) => String(text ?? '').replace(/\|/g, '\\|');
const flagGroups = new Map();
for (const flag of FLAGS) {
    const list = flagGroups.get(flag.group) || [];
    list.push(flag);
    flagGroups.set(flag.group, list);
}
const paramOf = (flag) => {
    if (flag.type === 'boolean') return '`?' + flag.key + '=' + (flag.on ?? '1') + '`';
    if (flag.type === 'enum') return '`?' + flag.key + '=' + flag.values.join('\\|') + '`';
    if (flag.type === 'number') return '`?' + flag.key + '=<n>`';
    return '`?' + flag.key + '=<text>`';
};

const harnessLines = [];
harnessLines.push('# The render-test harness: flags and fixtures');
harnessLines.push('');
harnessLines.push('GENERATED by `scripts/generate-tables.mjs` from `fixtures/render-test/src/harness/flags.ts` (the flag registry) and `fixtures/render-test/src/fixtures/catalog.ts` (the fixture catalog) — do not edit; run `pnpm docs.tables`.');
harnessLines.push('');
harnessLines.push('THE URL IS THE FIXTURE. Every option of the harness (`fixtures/render-test`, `pnpm --filter plurid-render-test dev`) is a query flag; the SETUP button at the top-left expands into all of them — the layout switches on the live instance, the plane set / sizes / persistence re-create the application, everything else reloads the page — and rewrites the URL, so any state is shareable by pasting a link. A named FIXTURE is a set of flags (`?fixture=<name>`; its flags apply UNDER any explicit param, so a scenario can open a fixture and override one flag), optional link clicks, and the viewpoints the visual baselines are taken at. `?gallery=1` renders every fixture on one page (each in its own harness).');
harnessLines.push('');
harnessLines.push('## Flags');
harnessLines.push('');
harnessLines.push('`Applies` — `live`: the configuration prop of the mounted application; `remount`: a new application (no page load); `reload`: a page load (a startup-only option).');
harnessLines.push('');
for (const [group, list] of flagGroups) {
    harnessLines.push('### ' + group);
    harnessLines.push('');
    harnessLines.push('| Param | Default | Applies | Does | Exercises |');
    harnessLines.push('| --- | --- | --- | --- | --- |');
    for (const flag of list) {
        harnessLines.push(`| ${paramOf(flag)} | ${flag.default === undefined ? '-' : '`' + cell(flag.default) + '`'} | ${flag.apply} | ${cell(flag.description)} | ${cell(flag.exercises)} |`);
    }
    harnessLines.push('');
}
harnessLines.push('## Fixtures');
harnessLines.push('');
harnessLines.push('Verified by `fixtures/render-test/e2e/fixtures.spec.ts` (the generic invariants: boots without console errors, every shown plane measured, a declared size is the plane\'s box, the roots of a grid layout do not overlap in world X/Y, one minimap dot per shown plane, every on-screen link hit by itself, the space idle) and `visual.spec.ts` (a screenshot baseline per viewpoint under `e2e/__snapshots__/<platform>/`, compared on every run; `darwin` and `linux` baselines are committed, and the `linux` set is generated in the pinned `mcr.microsoft.com/playwright:v1.62.1-noble` container CI uses. Regenerate with `npx playwright test --config e2e/playwright.config.ts --project=visual --update-snapshots` from `fixtures/render-test`).');
harnessLines.push('');
harnessLines.push('| Fixture | Title | Flags | Steps | Viewpoints | Expectations |');
harnessLines.push('| --- | --- | --- | --- | --- | --- |');
for (const fixture of FIXTURES) {
    const flags = Object.entries(fixture.query).map(([key, value]) => '`' + key + '=' + value + '`').join(' ') || '-';
    const steps = (fixture.steps || []).map((step) => '`' + stepText(step) + '`').join(', ') || '-';
    const viewpoints = fixture.viewpoints.map((viewpoint) => '`' + viewpoint.name + '`').join(', ');
    harnessLines.push(`| \`${fixture.name}\` | ${cell(fixture.title)} — ${cell(fixture.description)} | ${flags} | ${steps} | ${viewpoints} | ${cell(expectationsText(fixture.expect))} |`);
}
harnessLines.push('');
harnessLines.push('## Assertion globals');
harnessLines.push('');
// the sentence is written by hand: it must name every global the harness publishes, and only those
const harnessSources = (directory) => readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory()) return harnessSources(path);
    return /\.tsx?$/.test(entry.name) ? [readFileSync(path, 'utf8')] : [];
});
const publishedNames = publishedGlobals(harnessSources(harness));
const unnamed = undocumentedGlobals(ASSERTION_GLOBALS, publishedNames);
const stale = namedGlobals(ASSERTION_GLOBALS).filter((name) => !publishedNames.includes(name));
if (unnamed.length || stale.length) {
    throw new Error('[docs.tables] the assertion globals in scripts/harness-tables.mjs are out of date: '
        + [...unnamed.map((name) => 'not described: ' + name), ...stale.map((name) => 'no longer published: ' + name)].join(', '));
}
harnessLines.push(ASSERTION_GLOBALS);
harnessLines.push('');

emit('docs/HARNESS.md', harnessLines.join('\n'), FLAGS.length + ' flags, ' + FIXTURES.length + ' fixtures');
// #endregion harness


// ---------------------------------------------------------------------------------------------------
// docs/LOOKS.md — the token table and the twelve presets, from the themes package
const themesPackage = resolve(root, 'packages/plurid-utilities/plurid-themes');
const themesDistribution = resolve(themesPackage, 'distribution/index.js');
if (!existsSync(themesDistribution)) {
    console.error('[docs.tables] build @plurid/plurid-themes first (' + themesDistribution + ' is missing)');
    process.exit(1);
}
const themes = require(themesDistribution);
const swatch = (color) => '<svg width="14" height="14" viewBox="0 0 14 14" style="vertical-align:middle"><rect width="14" height="14" rx="3" fill="' + color + '" stroke="#8884" /></svg>';
const lookLines = [];
lookLines.push('# Looks');
lookLines.push('');
lookLines.push('GENERATED by `scripts/generate-tables.mjs` from `LOOK_TOKENS` / `LOOK_BASES` in `@plurid/plurid-themes` — do not edit; run `pnpm docs.tables`. The look is the one vocabulary every piece of engine chrome is drawn from: ' + themes.LOOK_TOKENS.length + ' tokens, emitted as `--plurid-<token>` custom properties on the application\'s element (`[data-plurid-application="<id>"]`), derived by `deriveLook` from a base of a few colours. Set it with `look` (a preset name, a base, or `{ preset, tokens }`); override any token from CSS with a more specific selector. The vocabulary and its rules: [DESIGN.md](./DESIGN.md); the knob and the slots: [CONTROL_SURFACE.md](./CONTROL_SURFACE.md#the-look).');
lookLines.push('');
lookLines.push('## The presets');
lookLines.push('');
lookLines.push('| look | scheme | space | surface | ink | accent | grid |');
lookLines.push('| --- | --- | --- | --- | --- | --- | --- |');
for (const name of themes.LOOK_NAMES) {
    const base = themes.LOOK_BASES[name];
    const isDefault = name === themes.DEFAULT_LOOK_NAME ? ' (default)' : '';
    lookLines.push('| `' + name + '`' + isDefault + ' | ' + base.scheme + ' | ' + swatch(base.space) + ' `' + base.space + '` | ' + swatch(base.surface) + ' `' + base.surface + '` | ' + swatch(base.ink) + ' `' + base.ink + '` | ' + swatch(base.accent) + ' `' + base.accent + '` | ' + (base.grid === false ? 'off' : 'on') + ' |');
}
lookLines.push('');
lookLines.push('## The tokens');
lookLines.push('');
lookLines.push('The value column is the default look\'s (`' + themes.DEFAULT_LOOK_NAME + '`).');
lookLines.push('');
const defaultLook = themes.looks[themes.DEFAULT_LOOK_NAME];
let lastGroup = '';
for (const token of themes.LOOK_TOKENS) {
    if (token.group !== lastGroup) {
        lastGroup = token.group;
        lookLines.push('');
        lookLines.push('### ' + token.group);
        lookLines.push('');
        lookLines.push('| token | property | ' + themes.DEFAULT_LOOK_NAME + ' | what it is |');
        lookLines.push('| --- | --- | --- | --- |');
    }
    lookLines.push('| `' + token.name + '` | `' + token.property + '` | `' + cell(defaultLook.tokens[token.name]) + '` | ' + cell(token.description) + ' |');
}
lookLines.push('');
emit('docs/LOOKS.md', lookLines.join('\n'), themes.LOOK_TOKENS.length + ' tokens, ' + themes.LOOK_NAMES.length + ' looks');
